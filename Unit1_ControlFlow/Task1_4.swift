// Task 1.4 - Print the day name for numbers 1-7 using switch.
// Any other value prints "Invalid" (the default case).

let day = 3

switch day {
case 1: print("Monday")
case 2: print("Tuesday")
case 3: print("Wednesday")
case 4: print("Thursday")
case 5: print("Friday")
case 6: print("Saturday")
case 7: print("Sunday")
default: print("Invalid")
}
